#!/usr/bin/env python3
"""Render a remote external config that references personal rules in a GitHub repo."""

import argparse
from pathlib import Path
import re
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]


def render(repo, branch):
    base = f"https://raw.githubusercontent.com/{repo}/{quote(branch, safe='')}/"
    source = (ROOT / "config/custom.ini").read_text(encoding="utf-8")
    lines = ["; Generated by scripts/github_config.py from config/custom.ini."]
    for line in source.splitlines():
        if line.startswith("clash_rule_base=config/custom/"):
            line = "clash_rule_base=" + base + "config/" + line.split("config/custom/", 1)[1]
        elif line.startswith("ruleset=") and ",rules/custom/" in line:
            line = line.replace(",rules/custom/", "," + base + "rules/", 1)
        lines.append(line)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True, help="自己的 GitHub 仓库，例如 alice/clash-rules")
    parser.add_argument("--branch", default="main", help="仓库分支，默认 main；按实际填写")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9-]+/[A-Za-z0-9_.-]+", args.repo):
        parser.error("--repo 格式必须是 owner/repo")
    if not args.branch or any(c.isspace() for c in args.branch):
        parser.error("--branch 不能为空或包含空白")
    destination = ROOT / "config/github.ini"
    destination.write_text(render(args.repo, args.branch), encoding="utf-8")
    branch = quote(args.branch, safe="")
    print(f"已生成 {destination.relative_to(ROOT)}，请将它与 rules/ 一起提交到自己的仓库。")
    print(f"外部配置 URL：https://raw.githubusercontent.com/{args.repo}/{branch}/config/github.ini")
    print("个人规则以后可直接在 GitHub 网页编辑；修改 custom.ini 后需重新生成 github.ini。")


if __name__ == "__main__":
    main()
