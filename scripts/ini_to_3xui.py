#!/usr/bin/env python3
"""Convert config/github.ini (ACL4SSR) into a 3x-ui Clash routing YAML map.

3x-ui only imports ``proxy-groups``, ``rule-providers`` and ``rules`` from a
remote routing source; node definitions (``proxies``) are always generated by
the panel. The output therefore never contains ``proxies``, and proxy groups
reference only other groups or Clash built-ins, never a concrete node name
(3x-ui validates remote sources against a dummy ``validation-node``).

The YAML writer is intentionally tiny and stdlib-only: the document shape is
fixed (maps, lists, strings, ints, bools), so no YAML dependency is needed.
"""

from pathlib import Path
from urllib.parse import urlparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config/github.ini"
OUTPUT = ROOT / "config/3xui.yaml"

RAW_GITHUB = "https://raw.githubusercontent.com/"
JSDELIVR = "https://cdn.jsdelivr.net/gh/"
BUILTINS = {"DIRECT", "REJECT", "REJECT-DROP", "PASS", "COMPATIBLE", "GLOBAL"}
CATCH_ALL = {"FINAL", "MATCH"}
TEST_URL_TYPES = {"url-test", "fallback", "load-balance"}


def to_jsdelivr(url: str) -> str:
    """Rewrite raw.githubusercontent.com URLs so clients behind the GFW can fetch them."""
    if not url.startswith(RAW_GITHUB):
        return url
    try:
        owner, repo, ref, path = url[len(RAW_GITHUB):].split("/", 3)
    except ValueError:
        return url
    return f"{JSDELIVR}{owner}/{repo}@{ref}/{path}"


def entries(path: Path):
    """Yield (key, value) pairs from the [custom] section, preserving order."""
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith((";", "#", "[")):
            continue
        key, separator, value = line.partition("=")
        if separator:
            yield key.strip(), value.strip()


def parse_group(spec: str) -> dict:
    """Parse one ACL4SSR ``custom_proxy_group`` line into a Mihomo group."""
    parts = [part.strip() for part in spec.split("`")]
    if len(parts) < 2 or not parts[0]:
        raise ValueError(f"bad custom_proxy_group: {spec}")

    group = {"name": parts[0], "type": parts[1] or "select"}
    proxies, filters, include_all = [], [], False

    for arg in parts[2:]:
        if not arg:
            continue
        if arg == ".*":
            include_all = True
        elif arg.startswith("[]"):
            ref = arg[2:].strip()
            if ref and ref.upper() not in CATCH_ALL:
                proxies.append(ref)
        elif arg.startswith("(") and arg.endswith(")"):
            filters.append(arg[1:-1])
        elif arg.lower().startswith(("http://", "https://")):
            group["url"] = arg
        elif re.fullmatch(r"\d+(,\d*){0,2}", arg):
            fields = arg.split(",")
            group["interval"] = int(fields[0])
            if len(fields) > 2 and fields[2]:
                group["tolerance"] = int(fields[2])
        else:
            proxies.append(arg)

    if include_all or filters:
        group["include-all"] = True
    if filters:
        group["filter"] = "|".join(filters)
    if proxies:
        group["proxies"] = proxies
    if group["type"] in TEST_URL_TYPES:
        group.setdefault("url", "https://www.gstatic.com/generate_204")
        group.setdefault("interval", 300)
    return group


def provider_name(url: str, used: dict) -> str:
    """Stable, filename-derived rule-provider name with collision suffixes."""
    stem = Path(urlparse(url).path).stem or "ruleset"
    base = re.sub(r"[^A-Za-z0-9_-]+", "-", stem).strip("-").lower() or "ruleset"
    name, suffix = base, 2
    while name in used and used[name] != url:
        name, suffix = f"{base}-{suffix}", suffix + 1
    used[name] = url
    return name


def convert(source: Path = SOURCE) -> dict:
    """Return the 3x-ui remote routing document for an ACL4SSR INI."""
    groups, providers, rules = [], {}, []
    used_urls = {}

    for key, value in entries(source):
        if key == "custom_proxy_group":
            groups.append(parse_group(value))

    names = {group["name"] for group in groups}

    for key, value in entries(source):
        if key != "ruleset":
            continue
        policy, separator, target = value.partition(",")
        policy, target = policy.strip(), target.strip()
        if not separator or not policy or not target:
            raise ValueError(f"bad ruleset: {value}")

        if target.startswith("[]"):
            body = target[2:].strip()
            if body.split(",", 1)[0].upper() in CATCH_ALL:
                rules.append(f"MATCH,{policy}")
            else:
                rules.append(f"{body},{policy}")
            continue

        url = to_jsdelivr(target)
        name = provider_name(url, used_urls)
        providers[name] = {
            "type": "http",
            "behavior": "classical",
            "format": "text",
            "url": url,
            "path": f"./ruleset/{name}.yaml",
            "interval": 86400,
        }
        rules.append(f"RULE-SET,{name},{policy}")

    known = names | BUILTINS
    for group in groups:
        if "use" in group:
            raise ValueError(f"group {group['name']} must not use proxy-providers")
        for ref in group.get("proxies", []):
            if ref not in known:
                raise ValueError(f"group {group['name']} references unknown {ref!r}")

    for rule in rules:
        parts = [part.strip() for part in rule.split(",")]
        target = parts[-1]
        if target.lower() == "no-resolve" and len(parts) > 1:
            target = parts[-2]
        if parts[0].upper() == "RULE-SET" and parts[1] not in providers:
            raise ValueError(f"unknown rule-provider: {rule}")
        if target not in known:
            raise ValueError(f"rule target unknown: {rule}")

    return {"proxy-groups": groups, "rule-providers": providers, "rules": rules}


def _scalar(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def _dump(value, indent: int) -> str:
    pad = "  " * indent
    if isinstance(value, dict):
        lines = []
        for key, item in value.items():
            key_text = key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key, ensure_ascii=False)
            if isinstance(item, dict):
                if item:
                    lines.append(f"{pad}{key_text}:")
                    lines.append(_dump(item, indent + 1))
                else:
                    lines.append(f"{pad}{key_text}: {{}}")
            elif isinstance(item, list):
                if item:
                    lines.append(f"{pad}{key_text}:")
                    lines.append(_dump(item, indent + 1))
                else:
                    lines.append(f"{pad}{key_text}: []")
            else:
                lines.append(f"{pad}{key_text}: {_scalar(item)}")
        return "\n".join(lines)
    if isinstance(value, list):
        lines = []
        for item in value:
            if isinstance(item, dict):
                body = _dump(item, indent + 1).splitlines()
                lines.append(f"{pad}- {body[0].lstrip()}")
                lines.extend(body[1:])
            elif isinstance(item, list):
                lines.append(f"{pad}-")
                lines.append(_dump(item, indent + 1))
            else:
                lines.append(f"{pad}- {_scalar(item)}")
        return "\n".join(lines)
    return f"{pad}{_scalar(value)}"


def render(document: dict) -> str:
    return _dump(document, 0) + "\n"


def main() -> int:
    try:
        document = convert()
        text = render(document)
        if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == text:
            print("Unchanged: config/3xui.yaml")
            return 0
        OUTPUT.write_text(text, encoding="utf-8")
        print(
            f"Wrote config/3xui.yaml: {len(document['proxy-groups'])} groups, "
            f"{len(document['rule-providers'])} providers, {len(document['rules'])} rules"
        )
        return 0
    except (OSError, ValueError) as error:
        print(f"Conversion failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
